import { Stock, StockHistoricalPoint } from '../types';

// Helper to generate deterministic realistic historical curve for charts
function generateStockHistory(basePrice: number, volatility: number = 0.02) {
  const timeframes = ['1D', '1W', '1M', '1Y', 'ALL'] as const;
  const history: Record<string, StockHistoricalPoint[]> = {};

  const counts: Record<string, number> = {
    '1D': 24,
    '1W': 28,
    '1M': 30,
    '1Y': 36,
    'ALL': 40,
  };

  const labels: Record<string, (i: number, total: number) => string> = {
    '1D': (i) => {
      const hours = 9 + Math.floor(i * (6 / 24));
      const mins = (i % 4) * 15;
      return `${hours.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}`;
    },
    '1W': (i) => ['Mon 10am', 'Mon 2pm', 'Tue 10am', 'Tue 2pm', 'Wed 10am', 'Wed 2pm', 'Thu 10am', 'Thu 2pm', 'Fri 10am', 'Fri 2pm'][i % 10] || `Day ${i + 1}`,
    '1M': (i) => `Day ${i + 1}`,
    '1Y': (i) => ['Oct', 'Nov', 'Dec', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep'][i % 12],
    'ALL': (i) => `Q${(i % 4) + 1} '${20 + Math.floor(i / 8)}`,
  };

  // Seeded random-like wave
  timeframes.forEach((tf) => {
    const total = counts[tf];
    const points: StockHistoricalPoint[] = [];
    let current = tf === '1Y' || tf === 'ALL' ? basePrice * 0.75 : basePrice * 0.98;

    for (let i = 0; i < total; i++) {
      const cycle = Math.sin((i / total) * Math.PI * 3.5);
      const noise = Math.sin(i * 1.7) * 0.5 + Math.cos(i * 2.3) * 0.5;
      const trend = (i / total) * (basePrice - current);
      const delta = (cycle * 0.4 + noise * 0.6) * (basePrice * volatility);
      
      let p = current + delta + trend;
      if (i === total - 1) p = basePrice; // current price matches
      p = Math.max(p, basePrice * 0.4);

      const high = p * (1 + Math.abs(Math.sin(i * 3)) * 0.008);
      const low = p * (1 - Math.abs(Math.cos(i * 2)) * 0.008);
      const open = (high + low) / 2 + (Math.sin(i) * 0.003 * p);

      points.push({
        date: labels[tf](i, total),
        price: Math.round(p * 100) / 100,
        open: Math.round(open * 100) / 100,
        high: Math.round(high * 100) / 100,
        low: Math.round(low * 100) / 100,
        close: Math.round(p * 100) / 100,
        volume: Math.floor(150000 + Math.abs(Math.sin(i)) * 500000),
      });
    }
    history[tf] = points;
  });

  return history as Stock['history'];
}

